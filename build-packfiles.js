// Bakes the behaviour pack into the exe so the app can install it with no
// separate download. Re-run after editing the pack.
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "development_behavior_packs", "AI Companion - BP");
const OUT = path.join(__dirname, "src", "packfiles.js");
const TEXT = [".json", ".js"];

function walk(dir, base, into) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = path.relative(base, full).split(path.sep).join("/");
    if (fs.statSync(full).isDirectory()) walk(full, base, into);
    else into[rel] = fs.readFileSync(full);
  }
  return into;
}

const files = walk(SRC, SRC, {});
const lines = ["// Generated by build-packfiles.js - do not edit by hand.", "module.exports = {"];
for (const [rel, buf] of Object.entries(files)) {
  const isText = TEXT.includes(path.extname(rel));
  lines.push(
    "  " + JSON.stringify(rel) + ": { base64: " +
    JSON.stringify(buf.toString("base64")) + " }," + (isText ? "" : "")
  );
}
lines.push("};", "");
fs.writeFileSync(OUT, lines.join("\n"));

const version = JSON.parse(files["manifest.json"].toString("utf8")).header.version.join(".");
console.log("baked " + Object.keys(files).length + " files, pack version " + version);
for (const rel of Object.keys(files)) console.log("  " + rel + "  " + files[rel].length + " bytes");
